// G-code writer. One file per tool per operation. Metric, absolute.
//
// Coordinates: X0 Y0 = the stock's bottom-left corner (board y-down mm are
// flipped: Y = height - y). Z0 = top of the stock as given by the caller.

import type { Cut } from "./toolpaths";

export type Flavor = "mach3" | "generic";

export interface GcodeJob {
  title: string;
  notes: string[];
  cuts: Cut[];
  stockH: number; // mm, for the Y flip
  feed: number; // mm/min
  plunge: number; // mm/min
  rpm: number;
  safeZ: number; // rapid height, above everything
  approachZ: number; // rapid down to here before plunging (just above the material)
  flavor: Flavor;
}

export interface GcodeOut {
  text: string;
  seconds: number;
  cutLengthMm: number;
  moves: number;
}

const RAPID = 3000; // mm/min, for the time estimate only

const n = (v: number) => {
  const s = (Math.round(v * 1000) / 1000).toFixed(3).replace(/\.?0+$/, "");
  return s === "-0" ? "0" : s;
};
const clean = (s: string) => s.replace(/[()]/g, " ").replace(/[^\x20-\x7E]/g, "?");

export function writeGcode(job: GcodeJob): GcodeOut {
  const L: string[] = [];
  const X = (x: number) => x, Y = (y: number) => job.stockH - y;
  let seconds = 0, cut = 0, moves = 0;
  let cx = 0, cy = 0, cz = job.safeZ;
  const g0 = (x: number | null, y: number | null, z: number | null) => {
    const nx = x ?? cx, ny = y ?? cy, nz = z ?? cz;
    seconds += (Math.hypot(nx - cx, ny - cy, nz - cz) / RAPID) * 60;
    L.push("G0" + (x !== null ? ` X${n(X(nx))}` : "") + (y !== null ? ` Y${n(Y(ny))}` : "") + (z !== null ? ` Z${n(nz)}` : ""));
    cx = nx; cy = ny; cz = nz;
  };
  const g1 = (x: number | null, y: number | null, z: number | null, f: number) => {
    const nx = x ?? cx, ny = y ?? cy, nz = z ?? cz;
    const d = Math.hypot(nx - cx, ny - cy, nz - cz);
    if (d < 1e-4) return;
    seconds += (d / f) * 60;
    cut += d;
    moves++;
    L.push("G1" + (x !== null ? ` X${n(X(nx))}` : "") + (y !== null ? ` Y${n(Y(ny))}` : "") + (z !== null ? ` Z${n(nz)}` : "") + ` F${n(f)}`);
    cx = nx; cy = ny; cz = nz;
  };

  L.push(`(${clean(job.title)})`);
  for (const note of job.notes) L.push(`(${clean(note)})`);
  L.push(`(Generated by Kundekar. SIMULATE BEFORE CUTTING.)`);
  L.push(job.flavor === "mach3" ? "G21 G90 G17 G40 G49 G94" : "G21 G90 G17 G94");
  L.push(`G0 Z${n(job.safeZ)}`);
  L.push(`M3 S${Math.round(job.rpm)}`);

  for (const c of job.cuts) {
    const left = c.paths.slice();
    while (left.length) {
      // nearest path next; closed paths start at their nearest point, open ones at their nearer end
      let bi = 0, bp = 0, bd = Infinity, rev = false;
      left.forEach((p, i) => {
        if (c.closed) {
          for (let k = 0; k < p.length; k += 2) {
            const d = (p[k] - cx) ** 2 + (p[k + 1] - cy) ** 2;
            if (d < bd) { bd = d; bi = i; bp = k; }
          }
        } else {
          const d0 = (p[0] - cx) ** 2 + (p[1] - cy) ** 2, d1 = (p[p.length - 2] - cx) ** 2 + (p[p.length - 1] - cy) ** 2;
          if (d0 < bd) { bd = d0; bi = i; rev = false; }
          if (d1 < bd) { bd = d1; bi = i; rev = true; }
        }
      });
      const pi = c.paths.indexOf(left[bi]);
      const p = left.splice(bi, 1)[0];
      const pz = c.zs ? c.zs[pi] : null;
      let pts: number[], zz: number[] | null = null;
      if (c.closed) {
        pts = [...p.slice(bp), ...p.slice(0, bp), p[bp], p[bp + 1]]; // rotate, then close
      } else if (rev) {
        pts = [];
        for (let k = p.length - 2; k >= 0; k -= 2) pts.push(p[k], p[k + 1]);
        if (pz) zz = pz.slice().reverse();
      } else { pts = p; zz = pz; }
      const z0 = zz ? zz[0] : c.z;
      // Short hops over the work only lift just above the material; long moves go to safe Z.
      const hop = Math.hypot(pts[0] - cx, pts[1] - cy) < 10 && cz < job.safeZ;
      const lift = hop ? job.approachZ : job.safeZ;
      if (cz < lift) g0(null, null, lift);
      g0(pts[0], pts[1], null);
      g0(null, null, Math.max(job.approachZ, z0));
      g1(null, null, z0, job.plunge);
      for (let k = 2; k < pts.length; k += 2) g1(pts[k], pts[k + 1], zz ? zz[k / 2] : null, job.feed);
    }
  }
  g0(null, null, job.safeZ);
  L.push("M5");
  L.push("M30");
  L.push("");
  return { text: L.join("\n"), seconds, cutLengthMm: cut, moves };
}
